// Build 2 rerun of the credit-risk stress cases with the changed engine.
// Run from the repo root: npx vite-node docs/review/after/stress.ts
// Writes docs/review/after/stress-results.csv and stress-results.md, with the review's original
// outcome (docs/review/tools/credit-risk/results.csv) beside each case.
import { readFileSync, writeFileSync } from 'node:fs';
import { seedRecord } from '../../../src/data/localRepository';
import { daysBetween } from '../../../src/engine/dates';
import { forecast, roomToLend } from '../../../src/engine/forecast';
import { helpPlan } from '../../../src/engine/help';
import { stressCases, STRESS_TODAY } from '../../../src/engine/testing/stressCases';
import type { ForecastInput } from '../../../src/engine/types';
import { homeView } from '../../../src/engine/view';

function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i]!;
    if (q) {
      if (c === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') {
      row.push(cell);
      cell = '';
    } else if (c === '\n') {
      row.push(cell);
      rows.push(row);
      row = [];
      cell = '';
    } else cell += c;
  }
  const [head, ...body] = rows;
  return body.filter((r) => r.length > 1).map((r) => Object.fromEntries(head!.map((h, i) => [h, r[i] ?? ''])));
}

const before = Object.fromEntries(parseCsv(readFileSync('docs/review/tools/credit-risk/results.csv', 'utf8')).map((r) => [r.id, r]));
const cases: { id: string; scenario: string; input: ForecastInput }[] = [
  ...stressCases(),
  ...(['thabo', 'lerato', 'ayanda'] as const).map((p) => {
    const r = seedRecord(p, STRESS_TODAY);
    return { id: `P-${p}`, scenario: `Persona ${p} as seeded, with cash and an informal obligation`, input: { transactions: r.transactions, balance: r.balance, today: STRESS_TODAY, obligations: r.obligations } };
  }),
];

const R = Math.round;
const out = cases.map(({ id, scenario, input }) => {
  const f = forecast(input);
  const v = homeView(f);
  const h = helpPlan(input);
  const b = before[id];
  const budget = v.budget.kind === 'amount' ? `R${v.budget.amount}` : v.budget.kind;
  return {
    id,
    scenario,
    before: b ? `${b.state}; ${b.headline}; safe to spend R${b.safeToSpend}; safe to lend R${b.safeToLend}` : '',
    status: f.status + (f.unclearReason ? ` (${f.unclearReason})` : ''),
    income: f.income.status,
    confidence: f.confidence,
    headline: f.status === 'unclear' ? 'Not enough to tell' : `${v.headline.label} ${f.headlineDate}`,
    band: `${f.band.from} to ${f.band.to} (${daysBetween(f.band.from, f.band.to)} days)`,
    nextMoney: f.nextMoney ? f.nextMoney.typical : 'none expected',
    budget,
    reserve: f.reserve,
    roomToLend: roomToLend(input),
    rates: `${R(f.rates.optimistic)} / ${R(f.rates.central)} / ${R(f.rates.pessimistic)}`,
    notices: v.notices.map((n) => n.kind).join(', '),
    help: f.status === 'unclear' ? 'nothing suggested' : h.target === null ? `covered, set aside up to R${h.canSetAside}` : `to ${h.target}: ${h.suggestions.map((s) => s.kind).join(', ')}`,
  };
});

const cols = Object.keys(out[0]!) as (keyof (typeof out)[0])[];
const esc = (x: unknown) => `"${String(x).replace(/"/g, '""')}"`;
writeFileSync('docs/review/after/stress-results.csv', [cols.join(','), ...out.map((r) => cols.map((c) => esc(r[c])).join(','))].join('\n') + '\n');
writeFileSync(
  'docs/review/after/stress-results.md',
  [
    '# Stress cases after build 2',
    '',
    `Generated by \`docs/review/after/stress.ts\` with the build 2 engine, today ${STRESS_TODAY} (a Tuesday) unless the case says otherwise. "Before" is the review's result from \`docs/review/tools/credit-risk/results.csv\`. Spend rates are rands a day (light / usual / heavy). Every case is also a permanent unit test in \`src/engine/stress.test.ts\`.`,
    '',
    '| id | scenario | before | after: status | income | confidence | headline | band | next money | daily budget | reserve | room to lend | notices |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...out.map((r) => `| ${r.id} | ${r.scenario} | ${r.before} | ${r.status} | ${r.income} | ${r.confidence} | ${r.headline} | ${r.band} | ${r.nextMoney} | ${r.budget} | R${r.reserve} | R${r.roomToLend} | ${r.notices} |`),
    '',
  ].join('\n'),
);
console.log(`wrote ${out.length} cases`);
